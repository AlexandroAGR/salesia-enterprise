D = Decimal
TAX = D("0.18")
NOW = datetime.now(timezone.utc)

engine = create_engine(settings.database_url)


def day_ago(n: int) -> datetime:
    return NOW - timedelta(days=n)


def sale_money(qty: int, unit: float) -> tuple[Decimal, Decimal, Decimal]:
    subtotal = (D(str(unit)) * qty).quantize(D("0.01"))
    tax = (subtotal * TAX).quantize(D("0.01"))
    return subtotal, tax, subtotal + tax


def wipe() -> None:
    """Vacía todas las tablas de la aplicación (mantiene el esquema)."""
    with engine.begin() as conn:
        tables = conn.execute(
            text(
                "SELECT tablename FROM pg_tables "
                "WHERE schemaname = 'public'"
            )
        ).scalars().all()
        if tables:
            names = ", ".join(f'"{t}"' for t in tables)
            conn.execute(
                text(
                    f"TRUNCATE {names} RESTART IDENTITY CASCADE"
                )
            )
    print(f"TRUNCATE de {len(tables)} tablas")


def reset_sequences() -> None:
    """Ajusta las secuencias IDENTITY al MAX(id) tras inserts con id fijo.

    ``GENERATED BY DEFAULT AS IDENTITY`` no avanza con inserts de id
    explícito: sin este paso, el siguiente INSERT del API chocaría con
    una clave primaria duplicada.
    """
    tables = (
        "companies", "roles", "users", "employees", "customers",
        "categories", "products", "sales", "sale_details",
        "payment_methods", "payments", "inventory", "inventory_movements",
        "datasets", "dataset_variables", "observations",
        "statistical_analyses", "statistical_results", "bayes_analyses",
        "random_variables", "insights", "reports", "audit_logs",
    )
    with engine.begin() as conn:
        for table in tables:
            seq = conn.execute(
                text(
                    "SELECT pg_get_serial_sequence('public.' || :t, 'id')"
                ),
                {"t": table},
            ).scalar()
            if seq:
                conn.execute(
                    text(
                        f"SELECT setval(:seq, "
                        f"GREATEST(COALESCE((SELECT MAX(id) FROM public."
                        f"{table}), 1), 1), true)"
                    ),
                    {"seq": seq},
                )
    print("Secuencias IDENTITY realineadas")


